import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import worker from '../sync-worker/src/index.js';
const db = new DatabaseSync(':memory:');
db.exec(`CREATE TABLE sync_records (owner_id TEXT, record_id TEXT, record_type TEXT, payload_json TEXT, deleted INTEGER, schema_version INTEGER, client_updated_at TEXT, server_updated_at TEXT, server_revision INTEGER, last_changed_device_id TEXT)`);
const env = { SYNC_API_TOKEN: 'test-only', SYNC_OWNER_ID: 'steeler', SYNC_DB: { prepare(sql) {return {bind(...args) {return {async all(){return {results:db.prepare(sql).all(...args)};},async first(){return db.prepare(sql).get(...args);}};}};} } };
const payload = {deviceName:'Bill’s "Mac"',backup:{exportedByDeviceName:'fallback',notes:'Sea → shore\n'.repeat(230000)}};
const insert = db.prepare('INSERT INTO sync_records VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)');
insert.run('steeler','global:full-data-sync','full-data-sync',JSON.stringify(payload),0,1,'2026-10-15','2026-10-15',2067,'mac');
insert.run('someone-else','private','full-data-sync','{}',0,1,'','',2068,'');
const get = (query='',token='test-only') => worker.fetch(new Request('https://example.test/v1/records'+query,{headers:{Authorization:`Bearer ${token}`}}),env);
let response = await get('?since=0&limit=20&type=full-data-sync');
assert.equal(response.status,200);
assert.equal(response.headers.get('Access-Control-Allow-Origin'),'*');
let body = await response.json();
assert.equal(body.records.length,1);
assert.deepEqual(body.records[0].payload,payload);
assert.equal(body.records[0].lastChangedDeviceName,payload.deviceName);
assert.equal(body.serverRevision,2067);
assert.equal((await get('','wrong')).status,401);
assert.deepEqual(await (await get('?since=2067')).json(),{ok:true,records:[],serverRevision:2067});
assert.equal((await (await get('?type=other')).json()).records.length,0);
insert.run('steeler','fallback','backup',JSON.stringify({backup:{exportedByDeviceName:'iPad'}}),1,1,'','',2069,'ipad');
body=await (await get('?since=2067&limit=1')).json();
assert.equal(body.records[0].lastChangedDeviceName,'iPad');
assert.equal(body.records[0].deleted,true);
insert.run('steeler','broken','backup','not JSON',0,1,'','',2070,'');
response=await get('?since=2069');
assert.equal(response.status,500);
assert.equal(response.headers.get('Access-Control-Allow-Origin'),'*');
assert.equal((await response.json()).ok,false);
console.log('PASS: large payload preserved; SQL filters, owner isolation, revisions, auth, CORS, fallback names, deletion and invalid JSON.');
db.close();
